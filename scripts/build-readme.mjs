#!/usr/bin/env node
// Writes README.md and README.zh-CN.md from data/skills.json, so the
// gallery, the Pro shelf and the showcase stay in step in both languages.
//
//   node scripts/build-readme.mjs
import { readFileSync, writeFileSync, existsSync } from 'node:fs'

const data = JSON.parse(readFileSync(new URL('../data/skills.json', import.meta.url), 'utf8'))
const site = (path, medium = 'readme') => `https://lookbk.dev${path}?${data.utm.replace('utm_medium=readme', `utm_medium=${medium}`)}`
const REPO = 'SHARPLEE00/lookbk-skills'
const n = data.free.length

for (const s of data.free) {
  if (!existsSync(new URL(`../media/skills/${s.slug}.gif`, import.meta.url))) throw new Error(`media/skills/${s.slug}.gif is missing`)
  if (!existsSync(new URL(`../skills/${s.slug}/SKILL.md`, import.meta.url))) throw new Error(`skills/${s.slug}/SKILL.md is missing`)
}

const pairs = (list) => list.reduce((rows, x, i) => (i % 2 ? rows[rows.length - 1].push(x) : rows.push([x]), rows), [])
const SERIES = {
  'footage-heroes': ['Footage Heroes', '视频首屏 Footage Heroes'],
  'motion-heroes': ['Motion Heroes', '动效首屏 Motion Heroes'],
  'launch-films': ['Launch Films', '发布片 Launch Films'],
}

function gallery(zh) {
  const cell = (s) =>
    `<td width="50%" valign="top"><a href="skills/${s.slug}"><img src="media/skills/${s.slug}.gif" alt="${s.name}" width="100%"></a><br><b><a href="skills/${s.slug}">${s.slug}</a></b><br>${zh ? s.makes_zh : s.makes}<br><sub>${zh ? '需要' : 'Needs'}: ${s.needs} · <a href="${site(`/skills/${s.slug}`)}">${zh ? '在 lookbk.dev 上看' : 'Live preview'}</a></sub></td>`
  return `<table>\n${pairs(data.free).map((r) => `<tr>\n${r.map(cell).join('\n')}${r.length < 2 ? '\n<td width="50%"></td>' : ''}\n</tr>`).join('\n')}\n</table>`
}

function shelf(zh) {
  const cell = (p) => `<td width="25%" valign="top"><a href="${site(`/skills/${p.slug}`, 'readme-pro')}"><img src="media/pro/${p.slug}.webp" alt="${p.name}" width="100%"></a><br><sub><b>${p.name}</b><br>${SERIES[p.series][zh ? 1 : 0]}</sub></td>`
  const rows = []
  for (let i = 0; i < data.pro.length; i += 4) rows.push(`<tr>\n${data.pro.slice(i, i + 4).map(cell).join('\n')}\n</tr>`)
  return `<table>\n${rows.join('\n')}\n</table>`
}

function showcase(zh) {
  const issue = `https://github.com/${REPO}/issues/new?template=showcase.yml`
  if (!data.showcase.length)
    return zh
      ? `还没有人投稿。用这些技能做了东西？[提交到展示区](${issue})，选中的会放在这里，并在 lookbk.dev 上署名展示。`
      : `Nothing here yet. Made something with these skills? [Add it to the showcase](${issue}) and we'll feature it here and on lookbk.dev, credited to you.`
  const line = (x) => `- [${x.title}](${x.url}) by [@${x.author}](https://x.com/${x.author}) · \`${x.skill}\``
  return `${data.showcase.map(line).join('\n')}\n\n${zh ? `[投稿你的作品 →](${issue})` : `[Add yours →](${issue})`}`
}

const badges = `[![Stars](https://img.shields.io/github/stars/${REPO}?style=flat&color=f0703f)](https://github.com/${REPO}/stargazers) [![License: MIT](https://img.shields.io/badge/license-MIT-1d1a17)](LICENSE) [![Skills](https://img.shields.io/badge/free%20skills-${n}-0f6b6b)](#the-skills) [![lookbk.dev](https://img.shields.io/badge/catalog-lookbk.dev-7a4fb0)](${site('/skills', 'badge')})`

